process.env.APP_DB_PATH = join(mkdtempSync(join(tmpdir(), 'vx-store-')), 'app.sqlite');
process.env.ADMIN_EMAIL = 'admin@example.test';
process.env.ADMIN_PASSWORD = 'test-password-with-24-characters';
const S = await import('../server/store.mjs');
const req = cookie => ({ method: 'POST', headers: { host: 'localhost', origin: 'http://localhost', 'x-vx-request': '1', cookie }, socket: { remoteAddress: '127.0.0.1' } });
async function signIn(action, body, cookie) {
  let saved;
  const result = await S.authRoute(req(cookie), { setHeader: (key, value) => { if (key === 'Set-Cookie') saved = value.split(';')[0]; } }, action, body, { limit() {} });
  return { ...result, cookie: saved || cookie };
}
test('shared CRUD authenticates admins, scopes customer records, rejects conflicts and preserves relationships', async () => {
  const admin = await signIn('login', { email: process.env.ADMIN_EMAIL, password: process.env.ADMIN_PASSWORD });
  assert.equal(admin.user.role, 'admin');
  assert.ok(admin.cookie);
  const alice = await signIn('register', { name: 'Alice', email: 'alice@example.test', password: 'alice-password-123' });
  const bob = await signIn('register', { name: 'Bob', email: 'bob@example.test', password: 'bob-password-12345' });
  assert.equal(S.snapshot(null).state.users.length, 0);
  assert.deepEqual(S.snapshot(S.sessionUser(req(alice.cookie))).state.users.map(u => u.id), [alice.user.id]);
  assert.ok(S.snapshot(S.sessionUser(req(admin.cookie))).state.users.every(u => !u.pass));
  const apply = (cookie, changes, revision = S.readStore().revision) => S.commitChanges(req(cookie), { revision, changes });
  const product = { id: 'new-download', name: 'New download', price: 99, mrp: 150, kind: 'Template', active: true };
  apply(admin.cookie, [{ name: 'products', id: product.id, record: product }]);
  assert.equal(S.sharedCatalog().products.find(p => p.id === product.id).price, 99);
  assert.throws(() => apply(alice.cookie, [{ name: 'products', id: product.id, record: { ...product, price: 1 } }]), { status: 403 });
  const oldRevision = S.readStore().revision;
  apply(admin.cookie, [{ name: 'products', id: product.id, record: { ...product, price: 100 } }]);
  assert.throws(() => apply(admin.cookie, [{ name: 'products', id: product.id, record: product }], oldRevision), { status: 409 });
  assert.equal(S.sharedCatalog().products.find(p => p.id === product.id).price, 100);
  assert.throws(() => S.commitChanges({ ...req(admin.cookie), headers: { ...req(admin.cookie).headers, origin: 'https://attacker.test' } }, { revision: S.readStore().revision, changes: [] }), { status: 403 });
  assert.throws(() => apply(alice.cookie, [{ name: 'users', id: alice.user.id, record: { ...S.sessionUser(req(alice.cookie)), role: 'admin' } }]), { status: 403 });
  assert.throws(() => apply(bob.cookie, [{ name: 'users', id: alice.user.id, record: { ...S.sessionUser(req(alice.cookie)), name: 'Hacked' } }]), { status: 403 });
  const cart = [{ type: 'product', ref: product.id, qty: 1 }];
  assert.throws(() => S.checkout(req(alice.cookie), { items: cart }, { priceCart, milestoneSchedule }), { status: 403 });
  const order = S.checkout(req(alice.cookie), { items: cart }, { priceCart, milestoneSchedule, demo: true });
  assert.equal(order.state.orders.length, 1);
  assert.equal(S.snapshot(S.sessionUser(req(bob.cookie))).state.orders.length, 0);
  assert.throws(() => apply(admin.cookie, [{ name: 'products', id: product.id, record: null }]), { status: 409 });
  assert.equal(S.sharedCatalog().products.find(p => p.id === product.id).price, 100);
  apply(admin.cookie, [{ name: 'orders', id: order.orderId, record: null }, { name: 'products', id: product.id, record: null }]);
  assert.equal(S.sharedCatalog().products.find(p => p.id === product.id), undefined);
  assert.throws(() => apply(admin.cookie, [{ name: 'users', id: 'u_admin', record: null }]), { status: 409 });
  await signIn('logout', {}, alice.cookie);
  assert.equal(S.sessionUser(req(alice.cookie)), null);
});
test('verified checkout is priced from the paid quote, is idempotent and cannot cross accounts', async () => {
  const alice = await signIn('login', { email: 'alice@example.test', password: 'alice-password-123' });
  const bob = await signIn('login', { email: 'bob@example.test', password: 'bob-password-12345' });
  const cart = [{ type: 'product', ref: S.sharedCatalog().products[0].id, qty: 1 }];
  const quote = priceCart(cart, { catalog: S.sharedCatalog(), gstPct: 18 });
  S.paymentReceipt('pay_test', { account: alice.user.email, orderId: 'razorpay_order', quote, items: cart, payPlan: 'full', due: quote.total });
  assert.throws(() => S.checkout(req(bob.cookie), { paymentId: 'pay_test', items: cart }, { priceCart, milestoneSchedule }), { status: 403 });
  const first = S.checkout(req(alice.cookie), { paymentId: 'pay_test', items: cart }, { priceCart, milestoneSchedule });
  const replay = S.checkout(req(alice.cookie), { paymentId: 'pay_test', items: cart }, { priceCart, milestoneSchedule });
  assert.equal(first.orderId, replay.orderId);
  assert.equal(replay.state.orders.filter(o => o.id === first.orderId).length, 1);
});
